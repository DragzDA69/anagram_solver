def square_off(rows):
    """Pad a glyph to HEIGHT rows of equal width, so glyphs concatenate cleanly."""
    width = max((len(row) for row in rows), default=0)
    padded = [row.ljust(width) for row in rows][:HEIGHT]
    return tuple(padded + [" " * width] * (HEIGHT - len(padded)))


CHARACTERS = {character: square_off(rows) for character, rows in CHARACTER_MAP.items()}


def for_char(char):
    return CHARACTERS.get(char)


def for_string(string):
    """The rows for a whole word, or None if any character has no glyph."""
    rows = ["" for _ in range(HEIGHT)]
    for char in string:
        char_rows = for_char(char)
        if char_rows is None:
            return None
        for i in range(HEIGHT):
            rows[i] += char_rows[i]
    return tuple(rows)


def width_of(string) -> int:
    """How many columns `string` would take, or 0 if it cannot be rendered."""
    rows = for_string(string)
    return max(len(row) for row in rows) if rows else 0
